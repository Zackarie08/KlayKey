CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, first_name VARCHAR(60) NOT NULL, last_name VARCHAR(60) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL, phone VARCHAR(30) NOT NULL DEFAULT '',
 address JSON NULL, role ENUM('customer','admin') NOT NULL DEFAULT 'customer', is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS product_categories (id VARCHAR(30) PRIMARY KEY,name VARCHAR(60) NOT NULL);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, slug VARCHAR(100) NOT NULL UNIQUE, sku VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL, category_id VARCHAR(30) NOT NULL, description TEXT NOT NULL, short_description VARCHAR(255) NOT NULL,
 price_cents INT UNSIGNED NOT NULL, stock_quantity INT UNSIGNED NOT NULL DEFAULT 0, layout VARCHAR(10) NULL,
 switch_type VARCHAR(20) NULL, connection_type VARCHAR(20) NULL, material VARCHAR(60) NOT NULL DEFAULT '',
 rgb_supported BOOLEAN NOT NULL DEFAULT TRUE, is_featured BOOLEAN NOT NULL DEFAULT FALSE, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 images JSON NOT NULL, compatibility JSON NOT NULL, option_field VARCHAR(40) NULL, option_value VARCHAR(50) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES product_categories(id), INDEX(category_id,layout), INDEX(option_field,option_value)
);
CREATE TABLE IF NOT EXISTS custom_builds (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,user_id BIGINT UNSIGNED NOT NULL,name VARCHAR(80) NOT NULL,
 configuration JSON NOT NULL,snapshot JSON NOT NULL,price_cents INT UNSIGNED NOT NULL,compatibility_version INT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id),INDEX(user_id,updated_at)
);
CREATE TABLE IF NOT EXISTS carts (id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 FOREIGN KEY(user_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS cart_items (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,cart_id BIGINT UNSIGNED NOT NULL,product_id BIGINT UNSIGNED NULL,
 name VARCHAR(160) NOT NULL,configuration JSON NULL,snapshot JSON NOT NULL,quantity INT UNSIGNED NOT NULL,
 FOREIGN KEY(cart_id) REFERENCES carts(id) ON DELETE CASCADE,FOREIGN KEY(product_id) REFERENCES products(id),CHECK(quantity BETWEEN 1 AND 20)
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,order_number VARCHAR(40) NOT NULL UNIQUE,user_id BIGINT UNSIGNED NOT NULL,
 shipping_address JSON NOT NULL,delivery_method VARCHAR(20) NOT NULL,payment_method VARCHAR(20) NOT NULL,
 subtotal_cents INT UNSIGNED NOT NULL,shipping_cents INT UNSIGNED NOT NULL,total_cents INT UNSIGNED NOT NULL,
 status ENUM('pending','confirmed','processing','ready-to-ship','shipped','completed','cancelled') NOT NULL DEFAULT 'confirmed',
 idempotency_key VARCHAR(80) NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id),UNIQUE(user_id,idempotency_key),INDEX(user_id,created_at)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,order_id BIGINT UNSIGNED NOT NULL,snapshot JSON NOT NULL,quantity INT UNSIGNED NOT NULL,
 unit_price_cents INT UNSIGNED NOT NULL,FOREIGN KEY(order_id) REFERENCES orders(id)
);
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,order_id BIGINT UNSIGNED NOT NULL UNIQUE,method VARCHAR(20) NOT NULL,
 reference VARCHAR(60) NOT NULL,status ENUM('simulated-paid','pending-cod') NOT NULL,amount_cents INT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(order_id) REFERENCES orders(id)
);
CREATE TABLE IF NOT EXISTS contact_messages (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,name VARCHAR(100) NOT NULL,email VARCHAR(254) NOT NULL,
 subject VARCHAR(160) NOT NULL,message TEXT NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (sid VARCHAR(128) PRIMARY KEY,data JSON NOT NULL,expires_at BIGINT NOT NULL,INDEX(expires_at));
