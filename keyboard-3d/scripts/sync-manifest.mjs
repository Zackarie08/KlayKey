import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const manifest=read('exports/keyboard_manifest.json');
if(!Array.isArray(manifest.layouts)||!manifest.bindings)throw Error('Unexpected manifest shape; aborting.');
const options=read('config/keyboard_options.json');
for(const [key,value] of Object.entries(options))manifest[key]=value;
manifest.compatibility=read('config/compatibility.json');
manifest.soundProfiles=read('config/sound_profiles.json');
fs.writeFileSync(path.join(root,'exports','keyboard_manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log('Manifest synced:',options.caseColors.length,'case colors,',options.caseFinishes.length,'finishes,',options.keycapThemes.length,'themes,',options.keycapMaterials.length,'materials,',options.switches.length,'switches,',options.rgbModes.length,'lighting modes,',options.connectionTypes.length,'connections.');